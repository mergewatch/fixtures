/**
 * Add two numbers.
 *
 * Returns the arithmetic sum of `a` and `b`.
 */
export function add(a: number, b: number): number {
  return a + b;
}

/**
 * Multiply two numbers.
 *
 * Returns the arithmetic product of `a` and `b`.
 */
export function multiply(a: number, b: number): number {
  return a * b;
}
